  function facts() {
    const T = window.TARGETS || {};
    const out = {
      overall: Number(T.overall) || 170,
      halfRack: Number(T.halfRack) || 200,
      training: Number(T.training) || 100,
      firstDate: '', lastDate: '', days: 0, totalPick: null, totalRows: null,
      teamUpdated: '', teamOk: null,
    };
    try {
      const index = window.V3Data && window.V3Data.current && window.V3Data.current.index;
      if (index && Array.isArray(index.dateKeys) && index.dateKeys.length) {
        const keys = index.dateKeys.slice().sort();
        out.firstDate = keys[0];
        out.lastDate = keys[keys.length - 1];
        out.days = keys.length;
      }
      if (index) {
        out.totalPick = Number(index.totalPick);
        out.totalRows = Number(index.totalRows);
      }
    } catch (error) {
      console.warn('guide facts', error);
    }
    // ชิป Target ของทีมเป็นตัวบอกสถานะที่ถูกต้องที่สุดอยู่แล้ว จึงอ่านสถานะจากชิปตัวนั้น
    const chip = document.querySelector('#teamTargetChip');
    if (chip && !chip.hidden) {
      out.teamOk = chip.dataset.state === 'team';
      // ชิปเขียนวันที่เป็น d/m/พ.ศ. ตามรูปแบบที่ใช้ทั้งเว็บ
      out.teamUpdated = (chip.textContent.match(/(\d{1,2}\/\d{1,2}\/\d{4})/) || [])[1] || '';
    }
    return out;
  }

